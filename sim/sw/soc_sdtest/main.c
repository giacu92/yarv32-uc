/*
 * SD card in SPI mode, end to end through axi4_lite_spi (M9b).
 *
 * Init at <= 400 kHz (CLKDIV 63: SCK period 128 core clocks), 80 clocks with
 * CS high, CMD0, CMD8 (R7 echo), CMD55/ACMD41 polled until ready, CMD58 (the
 * OCR's CCS picks block or byte addressing), CMD16 512. Then at the fast
 * clock: CMD17 block 0, CMD17 block 3, CMD18 blocks 5..7 + CMD12, and a
 * final CMD17 (block 6) to show the card is back in transfer state after the
 * CMD12. Every data block is checked byte for byte against sd_hash() and its
 * CRC16 against one computed here.
 *
 * The card image is generated by sim/soc/regress.py: 32-bit LE word i =
 * sd_hash(i). Runs unchanged on an SDHC (default) or an SDSC (+SDSC) model.
 */
#include <stdint.h>

#define SPI      0x10006000u
#define STATUS   (*(volatile uint32_t *)(SPI + 0x00))
#define CTRL     (*(volatile uint32_t *)(SPI + 0x04))
#define CLKDIV   (*(volatile uint32_t *)(SPI + 0x08))
#define CS       (*(volatile uint32_t *)(SPI + 0x0C))
#define TXD      (*(volatile uint32_t *)(SPI + 0x10))
#define RXD      (*(volatile uint32_t *)(SPI + 0x14))
#define RESULT   ((volatile uint32_t *)0x00002000u)

#ifndef FAST_DIV
#define FAST_DIV 1
#endif

static uint32_t sd_hash(uint32_t i)
{
    uint32_t w = i * 2654435761u;
    return w ^ (w >> 15) ^ 0x5D0C0DE5u;
}

static void fail(uint32_t phase, uint32_t detail, uint32_t got, uint32_t want)
{
    RESULT[1] = phase;
    RESULT[2] = detail;
    RESULT[3] = got;
    RESULT[4] = want;
    RESULT[0] = 0xBAD;
    for (;;)
        ;
}

static uint8_t xfer(uint8_t b)
{
    TXD = b;
    while (STATUS & 4) /* RX_EMPTY */
        ;
    return (uint8_t)RXD;
}

static void deselect(void)
{
    CS = 1;
    xfer(0xFF);
}

static uint8_t crc7(const uint8_t *d, int n)
{
    uint8_t c = 0;
    for (int i = 0; i < n; i++)
        for (int b = 7; b >= 0; b--) {
            int fb = ((c >> 6) ^ (d[i] >> b)) & 1;
            c = (c << 1) & 0x7F;
            if (fb) c ^= 0x09;
        }
    return (uint8_t)((c << 1) | 1);
}

/* Send a command (CS asserted) and return its R1: the first byte with bit 7
 * clear within 16 bytes, or 0xFF. */
static uint8_t cmd(uint8_t idx, uint32_t arg)
{
    uint8_t f[6] = {(uint8_t)(0x40 | idx), (uint8_t)(arg >> 24), (uint8_t)(arg >> 16),
                    (uint8_t)(arg >> 8), (uint8_t)arg, 0};
    f[5] = crc7(f, 5);
    CS = 0;
    for (int i = 0; i < 6; i++) xfer(f[i]);
    for (int i = 0; i < 16; i++) {
        uint8_t r = xfer(0xFF);
        if (!(r & 0x80)) return r;
    }
    return 0xFF;
}

static uint16_t crc16(uint16_t c, uint8_t b)
{
    c ^= (uint16_t)b << 8;
    for (int i = 0; i < 8; i++) c = (c & 0x8000) ? (uint16_t)((c << 1) ^ 0x1021) : (uint16_t)(c << 1);
    return c;
}

/* Receive one data block (token, 512 bytes, CRC) and check it is block blk. */
static void rx_block(uint32_t phase, uint32_t blk)
{
    uint8_t t = 0xFF;
    for (int i = 0; i < 1000 && t == 0xFF; i++) t = xfer(0xFF);
    if (t != 0xFE) fail(phase, 0x100 | blk, t, 0xFE);
    uint16_t c = 0;
    for (uint32_t i = 0; i < 512; i++) {
        uint32_t off = blk * 512 + i;
        uint8_t want = (uint8_t)(sd_hash(off >> 2) >> (8 * (off & 3)));
        uint8_t got = xfer(0xFF);
        if (got != want) fail(phase, off, got, want);
        c = crc16(c, got);
    }
    uint16_t rc = (uint16_t)(xfer(0xFF) << 8);
    rc |= xfer(0xFF);
    if (rc != c) fail(phase, 0x200 | blk, rc, c);
}

int main(void)
{
    uint8_t r;
    CTRL = 1;      /* enable, mode 0 */
    CLKDIV = 63;   /* 50 MHz / 128 = 390 kHz */
    CS = 1;
    for (int i = 0; i < 10; i++) xfer(0xFF); /* >= 74 clocks with CS high */

    if ((r = cmd(0, 0)) != 0x01) fail(1, 0, r, 0x01);
    deselect();
    if ((r = cmd(8, 0x1AA)) != 0x01) fail(2, 0, r, 0x01);
    uint32_t r7 = 0;
    for (int i = 0; i < 4; i++) r7 = (r7 << 8) | xfer(0xFF);
    if (r7 != 0x1AA) fail(2, 1, r7, 0x1AA);
    deselect();

    uint32_t n41 = 0;
    do {
        if ((r = cmd(55, 0)) & 0xFE) fail(3, n41, r, 0x01);
        deselect();
        r = cmd(41, 0x40000000u);
        deselect();
        n41++;
        if (n41 > 100) fail(3, 0x100, r, 0);
    } while (r == 0x01);
    if (r != 0) fail(3, 0x200, r, 0);
    RESULT[6] = n41;

    if ((r = cmd(58, 0)) != 0) fail(4, 0, r, 0);
    uint32_t ocr = 0;
    for (int i = 0; i < 4; i++) ocr = (ocr << 8) | xfer(0xFF);
    deselect();
    if (!(ocr & 0x80000000u)) fail(4, 1, ocr, 0x80000000u);
    uint32_t ccs = (ocr >> 30) & 1;
    RESULT[5] = ccs;
#define ADDR(b) (ccs ? (b) : (b) * 512u)

    if ((r = cmd(16, 512)) != 0) fail(5, 0, r, 0);
    deselect();

    CLKDIV = FAST_DIV;

    if ((r = cmd(17, ADDR(0))) != 0) fail(6, 0, r, 0);
    rx_block(6, 0);
    deselect();
    if ((r = cmd(17, ADDR(3))) != 0) fail(7, 0, r, 0);
    rx_block(7, 3);
    deselect();

    if ((r = cmd(18, ADDR(5))) != 0) fail(8, 0, r, 0);
    for (uint32_t b = 5; b <= 7; b++) rx_block(8, b);
    /* CMD12: the card keeps sending data while the command goes out; then
     * one stuff byte to discard, then R1, then busy (0x00) until 0xFF. */
    {
        uint8_t f[6] = {0x40 | 12, 0, 0, 0, 0, 0};
        f[5] = crc7(f, 5);
        for (int i = 0; i < 6; i++) xfer(f[i]);
        xfer(0xFF); /* stuff byte */
        r = 0xFF;
        for (int i = 0; i < 16 && (r & 0x80); i++) r = xfer(0xFF);
        if (r != 0) fail(9, 0, r, 0);
        int i;
        for (i = 0; i < 1000 && xfer(0xFF) != 0xFF; i++)
            ;
        if (i == 1000) fail(9, 1, i, 0);
    }
    deselect();

    if ((r = cmd(17, ADDR(6))) != 0) fail(10, 0, r, 0);
    rx_block(10, 6);
    deselect();

    RESULT[0] = 0x600D;
    for (;;)
        ;
}
